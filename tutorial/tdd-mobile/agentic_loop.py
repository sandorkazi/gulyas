def load_tasks():
    return json.loads(TASKS.read_text())


def load_budget(max_default):
    STATE_DIR.mkdir(exist_ok=True)
    if BUDGET_FILE.exists():
        spent = json.loads(BUDGET_FILE.read_text()).get("spent", 0)
    else:
        spent = 0
    return spent


def audit(task_id, phase, decision, detail=""):
    STATE_DIR.mkdir(exist_ok=True)
    line = {
        "ts": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "task": task_id,
        "phase": phase,
        "decision": decision,
        "detail": detail,
        # Sandbox context injected by herdr-agent-firejail; empty when run raw.
        "budget_id": os.environ.get("BUDGET_ID", ""),
        "agent": os.environ.get("HERDR_AGENT", ""),
        "worktree": os.environ.get("HERDR_WORKTREE", ""),
    }
    with AUDIT.open("a") as f:
        f.write(json.dumps(line) + "\n")


def check_guardrails():
    """Prove the repo guardrails hold. Offline-safe, short timeouts.

    PASS/FAIL verdicts apply only inside the wrapper jail (HERDR_WORKTREE
    set). Outside, probes report INFO so an unjailed shell can never
    "pass" — re-run via run-in-jail.sh for verdicts.
    """
    jailed = bool(os.environ.get("HERDR_WORKTREE"))
    print(f"guardrails [{'JAILED' if jailed else 'UNJAILLED (plain shell)'}] ...")
    verdicts = []

    # 1. filesystem: sibling worktrees must be invisible (wrapper blacklist).
    sib = Path.home() / ".herdr" / "worktrees"
    sib_visible = sib.exists() and any(sib.iterdir())
    if jailed:
        verdicts.append(not sib_visible)
        print(f"[guardrail:filesystem] siblings visible={sib_visible} — "
              + ("PASS" if not sib_visible
                 else "FAIL: inside jail but siblings visible — launch via herdr-agent-firejail"))
    else:
        print(f"[guardrail:filesystem] INFO siblings visible={sib_visible} "
              "(no jail here; compare with the jailed run)")

    # 2. network: direct TCP egress must DROP (netfilter) — expect timeout/refused.
    try:
        s = socket.create_connection(("93.184.216.34", 80), timeout=4)  # example.com
        s.close()
        if jailed:
            verdicts.append(False)
            print("[guardrail:netfilter] FAIL: direct TCP 93.184.216.34:80 CONNECTED inside the jail")
        else:
            print("[guardrail:netfilter] INFO direct TCP connects (no jail here)")
    except OSError as e:
        if jailed:
            verdicts.append(True)
            print(f"[guardrail:netfilter] PASS direct TCP blocked ({e})")
        else:
            print(f"[guardrail:netfilter] INFO direct TCP blocked ({e}) — host network, not the jail")

    # 3. proxy: a fetch via $http_proxy to a non-allowlisted host must 403
    #    (offline template: *every* host 403s; that is the point).
    proxy = os.environ.get("http_proxy") or os.environ.get("HTTP_PROXY", "")
    if not proxy:
        print("[guardrail:proxy] INFO no http_proxy in env — launch via run-in-jail.sh for the proxied path.")
    else:
        try:
            req = urllib.request.Request("http://example.com/")
            with urllib.request.urlopen(req, timeout=8) as r:
                if jailed:
                    verdicts.append(False)
                print(f"[guardrail:proxy] via {proxy} got {r.status} — "
                      "FAIL for offline template (expect 403)")
        except Exception as e:  # HTTPError 403 carries the proxy denial; that is PASS
            msg = str(e)
            if "403" in msg or "domain-not-allowed" in msg:
                if jailed:
                    verdicts.append(True)
                print(f"[guardrail:proxy] denied as designed ({msg[:120]}) — "
                      + ("PASS" if jailed else "INFO (proxy policy holds outside the jail too)"))
            else:
                print(f"[guardrail:proxy] WARN other error: {msg[:160]} (proxy up? port 8890?)")

    if not jailed:
        print("UNJAILLED — re-run inside the jail (run-in-jail.sh) for PASS/FAIL verdicts.")
        return 0
    print("GUARDRAILS: " + ("ALL HOLD" if verdicts and all(verdicts) else "BREACH — SEE NOTES ABOVE"))
    return 0 if verdicts and all(verdicts) else 1


def charge(spent, budget_max, task_id, phase):
    """One pytest run = 1 budget unit. Returns updated spent; exits 2 if empty."""
    if spent >= budget_max:
        audit(task_id, phase, "budget-exhausted", f"spent={spent} max={budget_max}")
        print(f"429 budget-exhausted at {task_id}/{phase} (spent={spent})", file=sys.stderr)
        sys.exit(2)
    spent += 1
    BUDGET_FILE.write_text(json.dumps({"spent": spent, "max": budget_max}))
    return spent


def run_pytest():
    p = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/test_todo_store.py", "-q"],
        cwd=BASE,
        capture_output=True,
        text=True,
    )
    tail = (p.stdout + p.stderr).strip().splitlines()
    tail = "\n".join(tail[-6:])
    return p.returncode, tail


def reset():
    SRC.write_text(FULL_SOURCES[0])
    TESTS.parent.mkdir(parents=True, exist_ok=True)
    TESTS.write_text(TEST_HEADER)
    STATE_DIR.mkdir(exist_ok=True)
    BUDGET_FILE.write_text(json.dumps({"spent": 0}))
    if AUDIT.exists():
        AUDIT.unlink()
    print("reset: src=stub v0, tests=header only, budget=0")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--show-plan", action="store_true")
    ap.add_argument("--reset", action="store_true")
    ap.add_argument("--check-guardrails", action="store_true")
    ap.add_argument("--budget-max", type=int,
                    default=int(os.environ.get("BUDGET_MAX", "50")))
    args = ap.parse_args()

    if args.reset:
        reset()
        return

    if args.check_guardrails:
        sys.exit(check_guardrails())

    tasks = load_tasks()
    if args.show_plan:
        for i, t in enumerate(tasks, 1):
            print(f"{i}. {t['id']} — {t['title']}\n   {t['spec']}")
        print(f"\nLoop per task: RED (append test, pytest must FAIL) -> "
              f"GREEN (src vN, pytest must PASS) -> REFACTOR (rerun, must PASS).")
        return

    if not SRC.exists() or not TESTS.exists():
        reset()
    spent = load_budget(args.budget_max)

    for step, task in enumerate(tasks, 1):
        tid = task["id"]
        print(f"\n=== [{step}/{len(tasks)}] {tid}: {task['title']} ===")

        # RED — append the task's test, expect failure.
        if TEST_SNIPPETS[tid] not in TESTS.read_text():
            TESTS.write_text(TESTS.read_text() + TEST_SNIPPETS[tid])
        spent = charge(spent, args.budget_max, tid, "red")
        rc, tail = run_pytest()
        audit(tid, "red", "fail" if rc else "unexpected-pass", tail.splitlines()[-1] if tail else "")
        print(f"RED rc={rc}\n{tail}")
        if rc == 0:
            print("WARN: RED passed — test does not discriminate. Stopping.", file=sys.stderr)
            sys.exit(1)

        # GREEN — cumulative patch, expect pass.
        SRC.write_text(FULL_SOURCES[step])
        spent = charge(spent, args.budget_max, tid, "green")
        rc, tail = run_pytest()
        audit(tid, "green", "pass" if rc == 0 else "fail", tail.splitlines()[-1] if tail else "")
        print(f"GREEN rc={rc}\n{tail}")
        if rc != 0:
            print("GREEN failed — patch incomplete. Stopping.", file=sys.stderr)
            sys.exit(1)

        # REFACTOR — normalize, rerun full suite, expect pass.
        SRC.write_text(SRC.read_text().rstrip() + "\n")
        spent = charge(spent, args.budget_max, tid, "refactor")
        rc, tail = run_pytest()
        audit(tid, "refactor", "pass" if rc == 0 else "fail", tail.splitlines()[-1] if tail else "")
        print(f"REFACTOR rc={rc}\n{tail}")
        if rc != 0:
            print("REFACTOR broke the suite. Stopping.", file=sys.stderr)
            sys.exit(1)

    print(f"\nDONE: {len(tasks)} tasks green, spent={spent}/{args.budget_max}. "
          f"Audit: {AUDIT.relative_to(BASE)}")


if __name__ == "__main__":
    main()
