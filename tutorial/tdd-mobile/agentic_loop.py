#!/usr/bin/env python3
"""Tutorial agentic TDD loop — stdlib only, no API key.

Runs *inside* the gulyas sandbox: launch it via
`environment/scripts/herdr-agent-firejail --template offline` so the loop
inherits the repo guardrails (Firejail filesystem jail + netfilter DROP +
allowlist proxy + per-task budget). See docs/tutorial-tdd-mobile-loop.md.

For each task in tasks.json, in order: RED (append failing test) ->
GREEN (cumulative src patch) -> REFACTOR (whitespace normalize + rerun).

Each pytest invocation costs 1 loop-budget unit and appends one JSONL audit
line, mirroring the proxy's own budget (429) + access.log shape. The loop
also honours the wrapper env (BUDGET_ID/BUDGET_MAX/HERDR_AGENT/HERDR_WORKTREE)
so `ps` + audit show which jailed task did what.

Usage:
  python3 agentic_loop.py [--show-plan] [--reset] [--budget-max N]
  python3 agentic_loop.py --check-guardrails   # prove the jail holds (offline-safe)
"""
